-- Учебное пересоздание схемы: выполняется только в отдельной учебной БД
DROP TABLE IF EXISTS retake_requests;
DROP TABLE IF EXISTS disciplines;
DROP TABLE IF EXISTS users;

CREATE TABLE disciplines (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login text NOT NULL UNIQUE,
    full_name text NOT NULL,
    role text NOT NULL
        CHECK (role IN ('Student', 'Teacher', 'HeadOfDepartment')),
    password_hash text NOT NULL
);

CREATE TABLE retake_requests (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number integer NOT NULL UNIQUE CHECK (number > 0),
    title text NOT NULL CHECK (char_length(title) BETWEEN 5 AND 80),
    description text NOT NULL CHECK (char_length(description) BETWEEN 10 AND 500),
    discipline_id integer NOT NULL REFERENCES disciplines (id),
    status text NOT NULL
        CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_user_id integer NOT NULL REFERENCES users (id),
    assignee_user_id integer NULL REFERENCES users (id),
    retake_date date NULL,
    retake_time time NULL,
    audience text NULL
);

-- Ускоряет фильтрацию заявок по статусу
CREATE INDEX retake_requests_status_idx ON retake_requests (status);

-- Ускоряет выборки заявок по дисциплине и соединение со справочником
CREATE INDEX retake_requests_discipline_id_idx ON retake_requests (discipline_id);
